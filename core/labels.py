"""Sample return label (PDF), made locally with reportlab: no carrier account, API call or cost.

It is deliberately and visibly fake: "SAMPLE / NOT VALID" banners and watermark, no carrier logo, no
carrier tracking number (the barcode carries our own RMA number) and sample addresses. Never send it
to a carrier.
"""

from __future__ import annotations

from io import BytesIO

from reportlab.graphics.barcode.code128 import Code128
from reportlab.lib.colors import Color, black, white
from reportlab.lib.units import inch
from reportlab.pdfgen.canvas import Canvas

WIDTH, HEIGHT = 4 * inch, 6 * inch  # standard 4x6 in thermal label
BANNER = "SAMPLE — NOT A VALID SHIPPING LABEL"
FOOTER = "Generated by the SOPO demo. Not affiliated with UPS. Do not use for shipping."
RETURN_ADDRESS = ("AxMatt Supply — Returns Dept.", "100 Sample Way", "Sample City, ST 00000", "(sample address)")


def filename(order_id: str) -> str:
    return f"SAMPLE-return-label-{order_id}.pdf"


def sample_return_label_pdf(label: str, order_id: str, part_number: str, quantity: int,
                            customer_email: str, issued_at: str) -> bytes:
    buf = BytesIO()
    c = Canvas(buf, pagesize=(WIDTH, HEIGHT), invariant=True)
    c.setTitle(f"SAMPLE return label {label} (not valid for shipping)")
    c.setAuthor("SOPO demo")
    m = 0.15 * inch
    right = WIDTH - m

    # Top banner
    c.setFillColor(black)
    c.rect(0, HEIGHT - 0.55 * inch, WIDTH, 0.55 * inch, stroke=0, fill=1)
    c.setFillColor(white)
    c.setFont("Helvetica-Bold", 10.5)
    c.drawCentredString(WIDTH / 2, HEIGHT - 0.25 * inch, BANNER)
    c.setFont("Helvetica-Bold", 9)
    c.drawCentredString(WIDTH / 2, HEIGHT - 0.43 * inch, "DEMO ONLY · VOID")
    c.setFillColor(black)

    def block(title: str, lines: tuple[str, ...], top: float, size: float = 9) -> float:
        c.setFont("Helvetica-Bold", 7)
        c.drawString(m, top, title)
        c.setFont("Helvetica", size)
        y = top - size - 2
        for line in lines:
            c.drawString(m, y, line)
            y -= size + 2
        return y

    y = block("FROM (CUSTOMER)", (customer_email, "(customer address on file — sample)"), HEIGHT - 0.75 * inch)
    c.line(m, y, right, y)
    y = block("SHIP TO", RETURN_ADDRESS, y - 12, size=11)
    c.line(m, y, right, y)

    c.setFont("Helvetica-Bold", 13)
    c.drawString(m, y - 20, "Carrier: UPS Ground (sample)")
    c.setFont("Helvetica", 8)
    c.drawString(m, y - 33, "Prepaid return · no carrier tracking number issued")
    y -= 42
    c.line(m, y, right, y)

    # Our RMA number, as a Code 128 barcode (not a carrier tracking number)
    c.setFont("Helvetica-Bold", 7)
    c.drawString(m, y - 12, "RETURN AUTHORIZATION (RMA)")
    barcode = Code128(label, barHeight=0.7 * inch, barWidth=1.0, quiet=False)
    barcode.drawOn(c, (WIDTH - barcode.width) / 2, y - 22 - 0.7 * inch)
    c.setFont("Helvetica-Bold", 12)
    c.drawCentredString(WIDTH / 2, y - 38 - 0.7 * inch, label)
    y -= 48 + 0.7 * inch
    c.line(m, y, right, y)

    block("REFERENCE", (f"Order: {order_id}", f"Part: {part_number}", f"Qty: {quantity}",
                        f"Issued: {issued_at}"), y - 12)

    # Bottom banner
    c.setFillColor(black)
    c.rect(0, 0, WIDTH, 0.4 * inch, stroke=0, fill=1)
    c.setFillColor(white)
    c.setFont("Helvetica-Bold", 6.3)
    c.drawCentredString(WIDTH / 2, 0.23 * inch, FOOTER)
    c.drawCentredString(WIDTH / 2, 0.1 * inch, BANNER)

    # Watermark over everything
    c.saveState()
    c.setFillColor(Color(0.85, 0.1, 0.1, alpha=0.28))
    c.translate(WIDTH / 2, HEIGHT / 2)
    c.rotate(55)
    c.setFont("Helvetica-Bold", 64)
    c.drawCentredString(0, -20, "SAMPLE")
    c.setFont("Helvetica-Bold", 30)
    c.drawCentredString(0, -60, "VOID · DEMO")
    c.restoreState()

    c.showPage()
    c.save()
    return buf.getvalue()
